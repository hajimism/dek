/**
 * Write `src/core/html-entities.ts`, the named character references an attribute value is decoded
 * with, from the list the HTML standard publishes:
 *
 *   bun scripts/html-entities.ts
 *
 * The table holds only what decoding needs: each name and its code points, and which names are
 * also read without their `;`.
 */
import { join } from "node:path";

const SOURCE = "https://html.spec.whatwg.org/entities.json";
const OUT = join(import.meta.dir, "..", "src", "core", "html-entities.ts");
/** The longest string literal a line holds, so biome leaves the lines as they are written. */
const LINE_CHARS = 95;

const response = await fetch(SOURCE);
if (!response.ok) {
  throw new Error(`${SOURCE}: ${response.status} ${response.statusText}`);
}
const entities = (await response.json()) as Record<string, { codepoints: number[] }>;

const named = new Map<string, string>();
const legacy: string[] = [];
for (const [reference, { codepoints }] of Object.entries(entities)) {
  const points = codepoints.map((point) => point.toString(16)).join("+");
  if (reference.endsWith(";")) {
    named.set(reference.slice(1, -1), points);
  } else {
    legacy.push(reference.slice(1));
  }
}
for (const name of legacy) {
  // The decoder looks a legacy name up among the named ones; the standard lists every one twice.
  const points = entities[`&${name}`]?.codepoints.map((point) => point.toString(16)).join("+");
  if (named.get(name) !== points) {
    throw new Error(`&${name} has no &${name}; with the same code points`);
  }
}

const sorted = (values: Iterable<string>): string[] =>
  [...values].sort((a, b) => (a < b ? -1 : a > b ? 1 : 0));

/** Words joined by spaces, as string literals of at most LINE_CHARS characters, one per line. */
function lines(words: string[]): string {
  const out: string[] = [];
  let line = "";
  for (const word of words) {
    if (line && line.length + 1 + word.length > LINE_CHARS) {
      out.push(line);
      line = word;
    } else {
      line = line ? `${line} ${word}` : word;
    }
  }
  if (line) {
    out.push(line);
  }
  return out.map((each) => `  "${each}",\n`).join("");
}

await Bun.write(
  OUT,
  `// Generated by \`bun scripts/html-entities.ts\` from ${SOURCE};
// run it again rather than edit.

/**
 * Every named character reference of the HTML standard, as \`<name>:<code points>\`: the name
 * without its \`;\`, and its code points in hex joined by \`+\`. Entries are separated by spaces.
 */
export const NAMED_REFERENCES = [
${lines(sorted([...named].map(([name, points]) => `${name}:${points}`)))}].join(" ");

/** The names the standard also reads without their \`;\`, as markup older than it writes them. */
export const LEGACY_REFERENCES = [
${lines(sorted(legacy))}].join(" ");
`,
);
