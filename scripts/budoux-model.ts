/**
 * Write `src/core/budoux/model.ts`, the Japanese model BudouX finds phrases with, from the one
 * BudouX publishes at the release in `src/core/budoux/VERSION`:
 *
 *   bun scripts/budoux-model.ts
 *
 * The model is a table of scores, each feature of the text around a place keyed by the characters
 * it looks at; the parser adds up the scores that match and breaks where the sum is positive.
 */
import { readFileSync } from "node:fs";
import { join } from "node:path";

const DIR = join(import.meta.dir, "..", "src", "core", "budoux");
const VERSION = readFileSync(join(DIR, "VERSION"), "utf8").trim();
const SOURCE = `https://raw.githubusercontent.com/google/budoux/v${VERSION}/budoux/models/ja.json`;
const OUT = join(DIR, "model.ts");
/** The longest string literal a line holds, so biome leaves the lines as they are written. */
const LINE_CHARS = 95;

const response = await fetch(SOURCE);
if (!response.ok) {
  throw new Error(`${SOURCE}: ${response.status} ${response.statusText}`);
}
const model = (await response.json()) as Record<string, Record<string, number>>;

const sorted = (values: Iterable<string>): string[] =>
  [...values].sort((a, b) => (a < b ? -1 : a > b ? 1 : 0));

/** Words joined by spaces, as string literals of at most LINE_CHARS characters, one per line. */
function lines(words: string[]): string {
  const out: string[] = [];
  let line = "";
  for (const word of words) {
    if (line && line.length + 1 + word.length > LINE_CHARS) {
      out.push(line);
      line = word;
    } else {
      line = line ? `${line} ${word}` : word;
    }
  }
  if (line) {
    out.push(line);
  }
  return out.map((each) => `    "${each}",\n`).join("");
}

let body = "";
for (const feature of sorted(Object.keys(model))) {
  const words = sorted(Object.keys(model[feature] ?? {})).map((key) => {
    // An entry is `<characters>:<score>`; a space, a quote, or a backslash would break the format.
    if (/[\s"\\]/u.test(key.replace(/\u3000/g, ""))) {
      throw new Error(`${feature} has a key the format cannot hold: ${JSON.stringify(key)}`);
    }
    return `${key}:${model[feature]?.[key]}`;
  });
  body += `  ${feature}: [\n${lines(words)}  ].join(" "),\n`;
}

await Bun.write(
  OUT,
  `// Generated by \`bun scripts/budoux-model.ts\` from ${SOURCE};
// run it again rather than edit. BudouX is Copyright 2021 Google LLC, under the Apache License,
// Version 2.0, in ./LICENSE.

/**
 * BudouX's Japanese model: for each feature, its entries as \`<characters>:<score>\`, separated by
 * spaces. The characters never hold an ASCII space; the score is an integer.
 */
export const JA_MODEL: Record<string, string> = {
${body}};
`,
);
console.log(`wrote ${OUT}`);
